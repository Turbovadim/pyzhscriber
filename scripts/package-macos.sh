#!/usr/bin/env bash
set -euo pipefail

PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DIST_DIR="$PROJECT_DIR/dist"
APP_DIR="$DIST_DIR/Pyzhscriber.app"
CONTENTS_DIR="$APP_DIR/Contents"
MACOS_DIR="$CONTENTS_DIR/MacOS"
RESOURCES_DIR="$CONTENTS_DIR/Resources"
INSTALL_APP="/Applications/Pyzhscriber.app"
INSTALL_STAGING="/Applications/.Pyzhscriber.installing.app"
INSTALL_BACKUP="/Applications/.Pyzhscriber.previous.app"

cargo build --locked --release --bin pyzhscriber --manifest-path "$PROJECT_DIR/Cargo.toml"

if [[ "$APP_DIR" != "$PROJECT_DIR"/dist/Pyzhscriber.app ]]; then
  echo "Unexpected bundle path: $APP_DIR" >&2
  exit 1
fi
rm -rf "$APP_DIR"
mkdir -p "$MACOS_DIR" "$RESOURCES_DIR"
cp "$PROJECT_DIR/target/release/pyzhscriber" "$MACOS_DIR/Pyzhscriber"
cp -R "$PROJECT_DIR/resources/." "$RESOURCES_DIR/"

# M5 GPUs expose their neural accelerators through the Metal 4 tensor API.
# Shipping a compiled library avoids a multi-second source compile on first launch.
METAL_SOURCE="$(find "$PROJECT_DIR/target/release/build" \
  -path '*transcribe-cpp-sys-*/out/build/ggml/src/ggml-metal/autogenerated/ggml-metal-embed.metal' \
  -type f -print0 | xargs -0 ls -t | head -n 1)"
if [[ ! -f "$METAL_SOURCE" ]]; then
  echo "Generated Metal source not found." >&2
  exit 1
fi
METAL_AIR="$DIST_DIR/default-tensor.air"
xcrun -sdk macosx metal -O3 -std=metal4.0 \
  -DGGML_METAL_HAS_TENSOR=1 \
  -DGGML_METAL_HAS_BF16=1 \
  -DGGML_METAL_EMBED_LIBRARY=1 \
  -c "$METAL_SOURCE" -o "$METAL_AIR"
xcrun -sdk macosx metallib "$METAL_AIR" -o "$MACOS_DIR/default-tensor.metallib"
rm -f "$METAL_AIR"

ICONSET_DIR="$DIST_DIR/Pyzhscriber.iconset"
rm -rf "$ICONSET_DIR"
mkdir -p "$ICONSET_DIR"
for size in 16 32 128 256 512; do
  sips -z "$size" "$size" "$PROJECT_DIR/assets/app-icon.png" \
    --out "$ICONSET_DIR/icon_${size}x${size}.png" >/dev/null
  retina_size=$((size * 2))
  sips -z "$retina_size" "$retina_size" "$PROJECT_DIR/assets/app-icon.png" \
    --out "$ICONSET_DIR/icon_${size}x${size}@2x.png" >/dev/null
done
iconutil -c icns "$ICONSET_DIR" -o "$RESOURCES_DIR/Pyzhscriber.icns"
rm -rf "$ICONSET_DIR"

cat > "$CONTENTS_DIR/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleDevelopmentRegion</key><string>en</string>
  <key>CFBundleDisplayName</key><string>Pyzhscriber</string>
  <key>CFBundleExecutable</key><string>Pyzhscriber</string>
  <key>CFBundleIconFile</key><string>Pyzhscriber</string>
  <key>CFBundleIdentifier</key><string>com.yolki.pyzhscriber</string>
  <key>CFBundleName</key><string>Pyzhscriber</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>0.1.0</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>LSMinimumSystemVersion</key><string>13.0</string>
  <key>NSHighResolutionCapable</key><true/>
  <key>NSMicrophoneUsageDescription</key><string>Pyzhscriber records speech only while the transcription shortcut is held.</string>
  <key>NSPrincipalClass</key><string>NSApplication</string>
</dict>
</plist>
PLIST

SIGN_IDENTITY="${PYZHSCRIBER_SIGN_IDENTITY:-}"
if [[ -z "$SIGN_IDENTITY" ]]; then
  SIGN_IDENTITY="$(security find-identity -v -p codesigning | sed -n 's/.*"\(Apple Development:[^"]*\)".*/\1/p' | head -n 1)"
fi
if [[ -z "$SIGN_IDENTITY" ]]; then
  echo "No Apple Development signing identity found." >&2
  exit 1
fi

codesign --force --deep --options runtime --timestamp=none \
  --entitlements "$PROJECT_DIR/resources/Pyzhscriber.entitlements" \
  --sign "$SIGN_IDENTITY" "$APP_DIR"
codesign --verify --deep --strict --verbose=2 "$APP_DIR"

if [[ "$INSTALL_APP" != "/Applications/Pyzhscriber.app" ]] ||
   [[ "$INSTALL_STAGING" != "/Applications/.Pyzhscriber.installing.app" ]] ||
   [[ "$INSTALL_BACKUP" != "/Applications/.Pyzhscriber.previous.app" ]]; then
  echo "Unexpected installation path." >&2
  exit 1
fi

rm -rf "$INSTALL_STAGING" "$INSTALL_BACKUP"
ditto "$APP_DIR" "$INSTALL_STAGING"
codesign --verify --deep --strict --verbose=2 "$INSTALL_STAGING"

# Swapping the bundle underneath a running instance leaves it with a deleted
# executable, which makes TCC reject it and the microphone go silent.
WAS_RUNNING=0
if pgrep -xq Pyzhscriber; then
  WAS_RUNNING=1
  pkill -x Pyzhscriber || true
  for _ in $(seq 1 50); do
    pgrep -xq Pyzhscriber || break
    sleep 0.1
  done
fi

if [[ -e "$INSTALL_APP" ]]; then
  mv "$INSTALL_APP" "$INSTALL_BACKUP"
fi
if ! mv "$INSTALL_STAGING" "$INSTALL_APP"; then
  if [[ -e "$INSTALL_BACKUP" ]]; then
    mv "$INSTALL_BACKUP" "$INSTALL_APP"
  fi
  exit 1
fi
if ! codesign --verify --deep --strict --verbose=2 "$INSTALL_APP"; then
  rm -rf "$INSTALL_APP"
  if [[ -e "$INSTALL_BACKUP" ]]; then
    mv "$INSTALL_BACKUP" "$INSTALL_APP"
  fi
  exit 1
fi
rm -rf "$INSTALL_BACKUP"

if [[ "$WAS_RUNNING" == 1 ]]; then
  # LaunchServices can briefly return error -600 right after the bundle is
  # replaced, so retry the background relaunch a few times before giving up.
  for _ in 1 2 3 4 5; do
    if open -g -a "$INSTALL_APP" 2>/dev/null; then
      break
    fi
    sleep 0.5
  done
fi

echo "$INSTALL_APP"
